package com.algorithm.boot.other.HWod.od2026;

import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;

class OD0920aTest {

    private final OD0920a solution = new OD0920a();

    @ParameterizedTest(name = "测试用例 {index}: n={0}, numbers={1}, expected={2}")
    @CsvSource(
            value = {
                    // ==================================================
                    // 1. 官方示例1
                    // ==================================================
                    "5 | -50,120,2000,50000,80 | 30,120,2000,50000",

                    // ==================================================
                    // 2. 官方示例2：四个分组的左边界
                    // ==================================================
                    "4 | 0,100,1000,10000 | 0,100,1000,10000",

                    // ==================================================
                    // 3. n=0，不处理任何元素
                    // ==================================================
                    "0 | 1,100,1000,10000 | 0,0,0,0",

                    // ==================================================
                    // 4. 四个分组右边界的前一个数
                    // ==================================================
                    "4 | 99,999,9999,999999 | 99,999,9999,999999",

                    // ==================================================
                    // 5. 负数按照绝对值分组
                    // ==================================================
                    "4 | -99,-999,-9999,-999999 | -99,-999,-9999,-999999",

                    // ==================================================
                    // 6. 负数形式的三个分组边界及最小值
                    // ==================================================
                    "4 | -100,-1000,-10000,-1000000 | 0,-100,-1000,-1010000",

                    // ==================================================
                    // 7. 同一分组内按原始正负值求和
                    // ==================================================
                    "8 | -50,80,-120,220,-2000,3000,-50000,60000" +
                            " | 30,100,1000,10000",

                    // ==================================================
                    // 8. 每组中的正负数完全抵消
                    // ==================================================
                    "8 | -99,99,-999,999,-9999,9999,-10000,10000 | 0,0,0,0",

                    // ==================================================
                    // 9. 最大正数和最小负数
                    // ==================================================
                    "2 | -1000000,1000000 | 0,0,0,0",

                    // ==================================================
                    // 10. 显式正号也是合法整数格式
                    // ==================================================
                    "4 | +50,-20,+100,-100 | 30,0,0,0",

                    // ==================================================
                    // 11. 多个0都属于第1组
                    // ==================================================
                    "4 | 0,0,0,0 | 0,0,0,0",

                    // ==================================================
                    // 12. 只有第4组有数据
                    // ==================================================
                    "3 | 10000,50000,-20000 | 0,0,0,40000",

                    // ==================================================
                    // 13. 只处理前n个成员
                    // ==================================================
                    // 后面的10000和1000000不能参与求和
                    "3 | 1,100,1000,10000,1000000 | 1,100,1000,0",

                    // ==================================================
                    // 14. n小于数组长度，后续成员属于其他分组
                    // ==================================================
                    // 只处理-99和-999
                    "2 | -99,-999,-9999,-99999 | -99,-999,0,0",

                    // ==================================================
                    // 15. n=1时只处理第一个成员
                    // ==================================================
                    "1 | -10000,99,999,9999 | 0,0,0,-10000",

                    // ==================================================
                    // 16. 输入顺序不影响分组结果
                    // ==================================================
                    "8 | 10000,1,1000,100,99,999,9999,-10000" +
                            " | 100,1099,10999,0"
            },
            delimiter = '|'
    )
    void testGroupNumbersByAbsoluteValue(
            int n,
            String numbersStr,
            String expectedStr) {

        String[] numbers = numbersStr.trim().split(",");
        int[] expected = parseArray(expectedStr);

        int[] actual = solution.groupNumbersByAbsoluteValue(n, numbers);

        assertArrayEquals(expected, actual);
    }

    private int[] parseArray(String str) {
        String[] parts = str.trim().split(",");
        int[] result = new int[parts.length];

        for (int i = 0; i < parts.length; i++) {
            result[i] = Integer.parseInt(parts[i].trim());
        }

        return result;
    }
}
