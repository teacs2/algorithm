    void testMaxBatch(String requestsStr, int expected) {

        int[][] requests = parseMatrix(requestsStr);

        int actual = solution.maxBatch(requests);

        assertEquals(expected, actual);
    }

    /**
     * 最大规模测试：
     * <p>
     * 构造100000个互不重叠的单点区间：
     * <p>
     * [0,0]
     * [1,1]
     * [2,2]
     * ...
     * <p>
     * 所以100000个全部可以选择。
     */
    @Test
    void testMaxN() {
        int n = 100000;

        int[][] requests = new int[n][2];

        for (int i = 0; i < n; i++) {
            requests[i][0] = i;
            requests[i][1] = i;
        }

        assertEquals(
                100000,
                solution.maxBatch(requests)
        );
    }

    /**
     * 将：
     * <p>
     * [[1,3],[2,5],[4,7]]
     * <p>
     * 转换为：
     * <p>
     * new int[][]{
     * {1,3},
     * {2,5},
     * {4,7}
     * }
     */
    private int[][] parseMatrix(String str) {

        String s = str.replace(" ", "").trim();

        if ("[]".equals(s)) {
            return new int[0][0];
        }

        // 去掉最外面的 [[ 和 ]]
        s = s.substring(2, s.length() - 2);

        String[] rows = s.split("\\],\\[");

        int[][] result = new int[rows.length][];

        for (int i = 0; i < rows.length; i++) {

            String[] nums = rows[i].split(",");

            result[i] = new int[nums.length];

            for (int j = 0; j < nums.length; j++) {
                result[i][j] = Integer.parseInt(nums[j]);
            }
        }

        return result;
    }
