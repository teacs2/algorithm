package com.algorithm.boot.other.HWod.od2026;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

import java.util.Arrays;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;

class OD0826bTest {

    private final OD0826b solution = new OD0826b();

    @ParameterizedTest(
            name = "测试用例 {index}: s={0}, expected={1}"
    )
    @CsvSource(
            value = {
                    // ==================================================
                    // 1. 官方示例1
                    // ==================================================
                    //
                    // 删除1：abca -> aca
                    // 删除2：abca -> aba
                    "abca | [1,2]",

                    // ==================================================
                    // 2. 官方示例2
                    // ==================================================
                    "abcd | []",

                    // ==================================================
                    // 3. 最小长度：两个相同字符
                    // ==================================================
                    //
                    // aa：
                    // 删除0 -> a
                    // 删除1 -> a
                    //
                    // 单字符也是回文
                    "aa | [0,1]",

                    // ==================================================
                    // 4. 最小长度：两个不同字符
                    // ==================================================
                    //
                    // ab：
                    // 删除任意一个，剩下一个字符
                    // 都是回文
                    "ab | [0,1]",

                    // ==================================================
                    // 5. 原字符串已经是奇数长度回文
                    // ==================================================
                    //
                    // aba
                    //
                    // 只有删除中间b：
                    // aba -> aa
                    "aba | [1]",

                    // ==================================================
                    // 6. 原字符串已经是偶数长度回文
                    // ==================================================
                    //
                    // abba
                    //
                    // 删除任意一个中间b：
                    // -> aba
                    "abba | [1,2]",

                    // ==================================================
                    // 7. 所有字符相同
                    // ==================================================
                    //
                    // 删除任何位置都仍然是回文
                    "aaaa | [0,1,2,3]",

                    // ==================================================
                    // 8. 中央存在较长相同字符区域
                    // ==================================================
                    //
                    // abbbbba
                    //
                    // 中间5个b任意删除一个：
                    // 都得到abbbba
                    "abbbbba | [1,2,3,4,5]",

                    // ==================================================
                    // 9. 偶数回文，中间两个字符可删除
                    // ==================================================
                    "abcddcba | [3,4]",

                    // ==================================================
                    // 10. 只能删除右边的不匹配字符
                    // ==================================================
                    //
                    // aab
                    //
                    // 删除b：
                    // aa
                    "aab | [2]",

                    // ==================================================
                    // 11. 只能删除左边的不匹配字符
                    // ==================================================
                    //
                    // abb
                    //
                    // 删除a：
                    // bb
                    "abb | [0]",

                    // ==================================================
                    // 12. 不匹配发生在中间
                    // ==================================================
                    //
                    // abcca
                    //
                    // 第一对不匹配：
                    // b 和 c
                    //
                    // 删除b：
                    // acca -> 回文
                    "abcca | [1]",

                    // ==================================================
                    // 13. 中间两个位置都可以删除
                    // ==================================================
                    //
                    // abdcba
                    //
                    // 删除d -> abcba
                    // 删除c -> abdba
                    "abdcba | [2,3]",

                    // ==================================================
                    // 14. 已经是回文，但是只有正中心可以删除
                    // ==================================================
                    "abcba | [2]",

                    // ==================================================
                    // 15. 中心有三个相同字符
                    // ==================================================
                    //
                    // baaab
                    //
                    // 删除任意一个a：
                    // baab
                    "baaab | [1,2,3]",

                    // ==================================================
                    // 16. 完全无法通过一次删除变成回文
                    // ==================================================
                    "abcde | []",

                    // ==================================================
                    // 17. 外层有很多相同字符
                    // 检查第一处不匹配是否正确定位
                    // ==================================================
                    //
                    // aabcbaa
                    //
                    // 删除c：
                    // aabbaa -> 回文
                    "aabcbaa | [3]"
            },
            delimiter = '|'
    )
    void testFindDeletionIndices(String s, String expectedStr) {

        int[] expected = parseArray(expectedStr);

        int[] actual = solution.findDeletionIndices(s);

        System.out.println(
                "\ns        = " + s
                        + "\nexpected = " + Arrays.toString(expected)
                        + "\nactual   = " + Arrays.toString(actual)
        );

        assertArrayEquals(expected, actual);
    }

    /**
     * 最大长度测试：
     * <p>
     * 100000个a。
     * <p>
     * 删除任何一个字符，
     * 剩下的仍然全部是a，所以所有下标都合法。
     */
    @Test
    void testMaxLength() {
        int n = 100000;

        char[] chars = new char[n];
        Arrays.fill(chars, 'a');

        String s = new String(chars);

        int[] expected = new int[n];

        for (int i = 0; i < n; i++) {
            expected[i] = i;
        }

        int[] actual = solution.findDeletionIndices(s);

        assertArrayEquals(expected, actual);
    }

    /**
     * "[1,2]"
     * <p>
     * ->
     * <p>
     * new int[]{1,2}
     * <p>
     * 同时支持：
     * <p>
     * "[]"
     */
    private int[] parseArray(String str) {
        String s = str.trim();

        if ("[]".equals(s)) {
            return new int[0];
        }

        if (s.startsWith("[") && s.endsWith("]")) {
            s = s.substring(1, s.length() - 1);
        }

        if (s.trim().isEmpty()) {
            return new int[0];
        }

        String[] parts = s.split(",");

        int[] result = new int[parts.length];

        for (int i = 0; i < parts.length; i++) {
            result[i] = Integer.parseInt(parts[i].trim());
        }

        return result;
    }
}