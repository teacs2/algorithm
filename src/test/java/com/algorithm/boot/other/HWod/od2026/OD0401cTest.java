package com.algorithm.boot.other.HWod.od2026;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

import static org.junit.jupiter.api.Assertions.assertEquals;

class OD0401cTest {

    private final OD0401c solution = new OD0401c();

    @ParameterizedTest(
            name = "测试用例 {index}: heightMap={0}, maxHeightDifference={1}, expected={2}"
    )
    @CsvSource(
            value = {
                    // ==================================================
                    // 1. 官方示例1
                    // ==================================================
                    // 唯一路径：1 -> 3 -> 5
                    "[[1,2],[3,5]] | 2 | 1",

                    // ==================================================
                    // 2. 官方示例2
                    // ==================================================
                    // 2 -> 3 -> 4，共有两条路径
                    "[[4,3],[3,2]] | 1 | 2",

                    // ==================================================
                    // 3. 官方示例3
                    // ==================================================
                    // 最低点1到相邻的3高度差为2，超过限制1
                    "[[1,3],[3,4]] | 1 | 0",

                    // ==================================================
                    // 4. 高度差恰好等于限制时允许移动
                    // ==================================================
                    // 1 -> 4 -> 5
                    // 1 -> 2 -> 5
                    "[[1,4],[2,5]] | 3 | 2",

                    // ==================================================
                    // 5. 最大高度差减小后两条路都被阻断
                    // ==================================================
                    "[[1,4],[2,5]] | 2 | 0",

                    // ==================================================
                    // 6. 负海拔也按照实际高度差判断
                    // ==================================================
                    // 唯一路径：-5 -> -3 -> -1
                    "[[-5,-4],[-3,-1]] | 2 | 1",

                    // ==================================================
                    // 7. 海拔从负数跨越到正数
                    // ==================================================
                    // -2 -> -1 -> 1
                    // -2 -> 0 -> 1
                    "[[-2,-1],[0,1]] | 2 | 2",

                    // ==================================================
                    // 8. 3×3递增地图
                    // ==================================================
                    // 只能向右或向下，共 C(4,2)=6 条路径
                    "[[1,2,3],[4,5,6],[7,8,9]] | 3 | 6",

                    // ==================================================
                    // 9. 高度限制使所有跨行移动失效
                    // ==================================================
                    "[[1,2,3],[4,5,6],[7,8,9]] | 2 | 0",

                    // ==================================================
                    // 10. 反向排列，验证向上和向左移动
                    // ==================================================
                    "[[9,8,7],[6,5,4],[3,2,1]] | 3 | 6",

                    // ==================================================
                    // 11. 非方形地图
                    // ==================================================
                    // 从左上角到右下角，共3条只向右或向下的路径
                    "[[1,2,3],[4,5,6]] | 3 | 3",

                    // ==================================================
                    // 12. 相同高度之间不能移动
                    // ==================================================
                    // 两个高度为2的位置分别形成一条路径
                    "[[1,2,2],[2,3,4]] | 1 | 2",

                    // ==================================================
                    // 13. 螺旋上升，路径需要使用四个方向
                    // ==================================================
                    // 1 -> 2 -> 3 -> 4 -> 5 -> 6 -> 7 -> 8 -> 9
                    "[[1,2,3],[8,9,4],[7,6,5]] | 1 | 1",

                    // ==================================================
                    // 14. 最低点与最高点相邻
                    // ==================================================
                    // 其他上升分支无法到达最高点，只有直接移动这一条路径
                    "[[1,100],[50,40]] | 99 | 1",

                    // ==================================================
                    // 15. 既可以直接到达，也可以绕行到达
                    // ==================================================
                    // 1 -> 10
                    // 1 -> 2 -> 9 -> 10
                    "[[1,10],[2,9]] | 9 | 2",

                    // ==================================================
                    // 16. 直接路径被限制阻断，但绕行路径仍然有效
                    // ==================================================
                    "[[1,10],[2,9]] | 8 | 1",

                    // ==================================================
                    // 17. 最低点和最高点不位于对角
                    // ==================================================
                    // 唯一路径：1 -> 3 -> 9
                    "[[5,1,2],[4,3,9]] | 6 | 1"
            },
            delimiter = '|'
    )
    void testCountClimbingPaths(
            String heightMapStr,
            int maxHeightDifference,
            int expected) {

        int[][] heightMap = parseMatrix(heightMapStr);

        int actual = solution.countClimbingPaths(
                heightMap,
                maxHeightDifference
        );

        assertEquals(expected, actual);
    }

    /**
     * 最大地图尺寸：10×10。
     * <p>
     * 地图按行从1递增到100，允许的最大高度差为10，
     * 因此只能向右或者向下移动。
     * 从左上角到右下角需要移动9次向右和9次向下，路径数为：
     * C(18,9) = 48620。
     */
    @Test
    void testMaximumMapSize() {
        int[][] heightMap = new int[10][10];

        for (int row = 0; row < 10; row++) {
            for (int col = 0; col < 10; col++) {
                heightMap[row][col] = row * 10 + col + 1;
            }
        }

        assertEquals(
                48620,
                solution.countClimbingPaths(heightMap, 10)
        );
    }

    /**
     * 将字符串形式的二维数组转换为 int[][]。
     * 例如：[[1,2],[3,5]]。
     */
    private int[][] parseMatrix(String str) {
        String content = str.replace(" ", "").trim();
        content = content.substring(2, content.length() - 2);

        String[] rows = content.split("\\],\\[");
        int[][] result = new int[rows.length][];

        for (int row = 0; row < rows.length; row++) {
            String[] values = rows[row].split(",");
            result[row] = new int[values.length];

            for (int col = 0; col < values.length; col++) {
                result[row][col] = Integer.parseInt(values[col]);
            }
        }

        return result;
    }
}
