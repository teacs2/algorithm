package com.algorithm.boot.other.HWod.od2026;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

import static org.junit.jupiter.api.Assertions.assertEquals;

class OD0906bTest {

    private final OD0906b solution = new OD0906b();

    @ParameterizedTest(name = "测试用例 {index}: n={0}, values={1}, expected={2}")
    @CsvSource(
            value = {
                    // ==================================================
                    // 1. 官方示例1
                    // ==================================================
                    // 1 -> 2 -> 3 -> 4 -> 5
                    // 10 + 5 + 8 + 3 + 15 = 41
                    "5 | 10,5,8,3,15 | 41",

                    // ==================================================
                    // 2. 官方示例2
                    // ==================================================
                    // 1 -> 2 -> 3 -> 4
                    // 10 + 1 + 1 + 100 = 112
                    "4 | 10,1,1,100 | 112",

                    // ==================================================
                    // 3. 只有一个关卡
                    // ==================================================
                    // 已经位于终点，获得第1关分数
                    "1 | 5 | 5",

                    // 单关卡也可能是负数
                    "1 | -999 | -999",

                    // ==================================================
                    // 4. 两个关卡
                    // ==================================================
                    // 只能1 -> 2
                    "2 | 5,10 | 15",

                    // 两个关卡都是负数，也必须到达终点
                    "2 | -5,-6 | -11",

                    // ==================================================
                    // 5. 应该跳过负数关卡
                    // ==================================================
                    // 1 -> 3
                    // 5 + 10 = 15
                    "3 | 5,-100,10 | 15",

                    // ==================================================
                    // 6. 最优路线最后一步跳2关
                    // ==================================================
                    // 1 -> 2 -> 4
                    // 移动：1、2
                    // 5 + 10 + 20 = 35
                    "4 | 5,10,-100,20 | 35",

                    // ==================================================
                    // 7. 最优路线先跳2，再走1
                    // ==================================================
                    // 1 -> 3 -> 4
                    // 5 + 10 + 20 = 35
                    "4 | 5,-100,10,20 | 35",

                    // ==================================================
                    // 8. 重点：不能连续跳两次2关
                    // ==================================================
                    //
                    // 如果错误允许：
                    // 1 -> 3 -> 5
                    // 10 + 5 + 10 = 25
                    //
                    // 但这是连续两次跳2，非法。
                    //
                    // 合法最优：
                    // 1 -> 3 -> 4 -> 5
                    // = 10 + 5 - 100 + 10
                    // = -75
                    //
                    // 或：
                    // 1 -> 2 -> 3 -> 5
                    // = -75
                    "5 | 10,-100,5,-100,10 | -75",

                    // ==================================================
                    // 9. 全部为负数
                    // ==================================================
                    //
                    // 合法路线：
                    //
                    // 1-2-3-4-5 = -13
                    // 1-2-3-5   = -12
                    // 1-2-4-5   = -12
                    // 1-3-4-5   = -12
                    //
                    // 1-3-5连续跳2，不合法
                    //
                    // 最大值 = -12
                    "5 | -5,-1,-1,-1,-5 | -12",

                    // ==================================================
                    // 10. 全部为正数
                    // ==================================================
                    // 都是正数，全部经过最划算
                    "5 | 1,1,1,1,1 | 5",

                    // ==================================================
                    // 11. 全部为0
                    // ==================================================
                    "5 | 0,0,0,0,0 | 0",

                    // ==================================================
                    // 12. 为了高分需要跳过中间负数
                    // ==================================================
                    //
                    // 最优：
                    // 1 -> 2 -> 4 -> 5
                    //
                    // 1 + 100 + 100 + 1
                    // = 202
                    //
                    // 移动：
                    // 1, 2, 1
                    // 合法
                    "5 | 1,100,-100,100,1 | 202",

                    // ==================================================
                    // 13. 重复负数
                    // ==================================================
                    // 检查DP在大量负数下是否仍正常工作
                    "4 | -10,-10,-10,-10 | -30",

                    // ==================================================
                    // 14. 极值分数
                    // ==================================================
                    // n=3，选择1 -> 3
                    "3 | 999,-999,999 | 1998",

                    // ==================================================
                    // 15. 不能为了跳负数连续跳2
                    // ==================================================
                    //
                    // 如果没有限制：
                    // 1 -> 3 -> 5 = 300
                    //
                    // 实际连续两次跳2非法。
                    //
                    // 合法路线必须至少经过一个-100
                    // 最大：100 + 100 - 100 + 100 = 200
                    "5 | 100,-100,100,-100,100 | 200"
            },
            delimiter = '|'
    )
    void testMaxScore(int n, String valuesStr, int expected) {
        int[] values = parseArray(valuesStr);

        int actual = solution.maxScore(n, values);

        assertEquals(expected, actual);
    }

    /**
     * 最大规模：
     *
     * n = 20
     * 每个关卡都是999。
     *
     * 因为全部都是正数，所以每关都走：
     *
     * 999 * 20 = 19980
     */
    @Test
    void testMaxNAllPositive() {
        int[] values = new int[20];

        for (int i = 0; i < values.length; i++) {
            values[i] = 999;
        }

        assertEquals(
                19980,
                solution.maxScore(20, values)
        );
    }

    /**
     * 将：
     *
     * "10,5,8,3,15"
     *
     * 转换成：
     *
     * new int[]{10,5,8,3,15}
     */
    private int[] parseArray(String str) {
        String[] parts = str.trim().split(",");

        int[] result = new int[parts.length];

        for (int i = 0; i < parts.length; i++) {
            result[i] = Integer.parseInt(parts[i].trim());
        }

        return result;
    }
}