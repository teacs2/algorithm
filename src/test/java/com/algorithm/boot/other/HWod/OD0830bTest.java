import static org.junit.jupiter.api.Assertions.assertTrue;

class OD0830bTest {

    private final OD0830b solution = new OD0830b();

    @ParameterizedTest(name = "测试用例 {index}: input={0}, expected={1}")
    @CsvSource(
            value = {
                    // ==================================================
                    // 1. 官方示例1
                    // ==================================================
                    // 1111：
                    // 100~110 = 10小时 -> 0元
                    // 180~190 = 10小时 -> 0元
                    //
                    // 2222：
                    // 200~210 = 10小时 -> 0元
                    //
                    // 3333：
                    // 150~165 = 15小时
                    // 超时3小时 -> 1元
                    //
                    // 因此：[3333,1] 排第一；
                    // 1111和2222都是0元，房间号小的1111在前。
                    "[[100,110,1111],[200,210,2222],[150,165,3333],[180,190,1111]]" +
                            " | [[3333,1],[1111,0],[2222,0]]",

                    // ==================================================
                    // 2. 官方示例2
                    // ==================================================
                    // 303：
                    // 10~30 = 20小时 -> 超时8小时 -> 1元
                    // 25~50 = 25小时 -> 超时13小时 -> 2元
                    // 总费用 = 3
                    //
                    // 201：
                    // 两次都是30小时
                    // 每次超时18小时 -> 每次2元
                    // 总费用 = 4
                    //
                    // 102：
                    // 两次都是30小时
                    // 每次2元
                    // 总费用 = 4
                    //
                    // 102和201费用相同，102房间号更小。
                    "[[10,30,303],[25,50,303],[40,70,201],[60,90,201],[100,130,102],[150,180,102]]" +
                            " | [[102,4],[201,4],[303,3]]",

                    // ==================================================
                    // 3. 恰好12小时
                    // ==================================================
                    // 免费时间边界
                    "[[0,12,100]] | [[100,0]]",

                    // ==================================================
                    // 4. 超过免费时间1小时
                    // ==================================================
                    // 13小时：
                    // 超时1小时，不足12小时按12小时算 -> 1元
                    "[[0,13,100]] | [[100,1]]",

                    // ==================================================
                    // 5. 总存放24小时
                    // ==================================================
                    // 24 - 12 = 12小时
                    // 正好一个收费周期 -> 1元
                    "[[0,24,100]] | [[100,1]]",

                    // ==================================================
                    // 6. 总存放25小时
                    // ==================================================
                    // 25 - 12 = 13小时
                    // ceil(13 / 12) = 2
                    "[[0,25,100]] | [[100,2]]",

                    // ==================================================
                    // 7. 同一个房间多条记录累计
                    // ==================================================
                    // 13小时 -> 1元
                    // 25小时 -> 2元
                    // 12小时 -> 0元
                    // 总费用3元
                    "[[0,13,100],[20,45,100],[50,62,100]] | [[100,3]]",

                    // ==================================================
                    // 8. 验证费用降序 + 房间号升序
                    // ==================================================
                    // 300 -> 2元
                    // 100 -> 2元
                    // 200 -> 1元
                    //
                    // 100与300费用相同，100在前
                    "[[0,25,300],[0,25,100],[0,13,200]]" +
                            " | [[100,2],[300,2],[200,1]]",

                    // ==================================================
                    // 9. 所有人都免费
                    // ==================================================
                    // 全部费用0，完全按照房间号升序
                    "[[0,1,300],[0,12,100],[5,10,200]]" +
                            " | [[100,0],[200,0],[300,0]]",

                    // ==================================================
                    // 10. 最大存放时间附近
                    // ==================================================
                    // duration = 99999
                    // overtime = 99987
                    // ceil(99987 / 12) = 8333
                    "[[0,99999,9999]] | [[9999,8333]]",

                    // ==================================================
                    // 11. 非常重要：
                    // 每一件快递独立享受12小时免费时间
                    // ==================================================
                    // 两次都是12小时，因此总费用仍然是0。
                    //
                    // 如果错误地把24小时合并后再计费，
                    // 会错误得到1元。
                    "[[0,12,100],[20,32,100]] | [[100,0]]",

                    // ==================================================
                    // 12. 同一个房间的记录不连续出现
                    // ==================================================
                    // 101：
                    // 13小时 -> 1
                    // 13小时 -> 1
                    // 总计2
                    //
                    // 102：
                    // 100小时
                    // 超时88小时
                    // ceil(88 / 12) = 8
                    "[[0,13,101],[0,100,102],[20,33,101]]" +
                            " | [[102,8],[101,2]]"
            },
            delimiter = '|'
    )
    void testCalculateFees(String inputStr, String expectedStr) {
        int[][] input = parseMatrix(inputStr);
        int[][] expected = parseMatrix(expectedStr);

        int[][] actual = solution.calculateFees(input);

        assertTrue(
                Arrays.deepEquals(expected, actual),
                () -> "\nexpected = " + Arrays.deepToString(expected)
                        + "\nactual   = " + Arrays.deepToString(actual)
        );
    }

    /**
     * 空数组。
     * 虽然题目约束N >= 1，
     * 但本地测试一下实现的健壮性。
     */
    @Test
    void testEmptyArray() {
        int[][] actual = solution.calculateFees(new int[0][0]);

        assertTrue(
                Arrays.deepEquals(new int[0][0], actual)
        );
    }

    /**
     * null。
     * 不属于题目合法输入，只用于本地健壮性测试。
     */
    @Test
    void testNull() {
        int[][] actual = solution.calculateFees(null);

        assertTrue(
                Arrays.deepEquals(new int[0][0], actual)
        );
    }

    /**
     * 将：
     *
     * [[100,110,1111],[200,210,2222]]
     *
     * 转换成：
     *
     * new int[][]{
     *     {100,110,1111},
     *     {200,210,2222}
     * }
     */
    private int[][] parseMatrix(String str) {
        String s = str.replace(" ", "").trim();

        if ("[]".equals(s)) {
            return new int[0][0];
        }

        // 去掉最外层的 [[ 和 ]]
        s = s.substring(2, s.length() - 2);

        String[] rows = s.split("\\],\\[");

        int[][] result = new int[rows.length][];

        for (int i = 0; i < rows.length; i++) {
            String[] nums = rows[i].split(",");

            result[i] = new int[nums.length];

            for (int j = 0; j < nums.length; j++) {
                result[i][j] = Integer.parseInt(nums[j]);
            }
        }

        return result;
    }
}