package com.algorithm.boot.other.HWod.od2026;

import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

import static org.junit.jupiter.api.Assertions.assertEquals;

class OD0906cTest {

    private final OD0906c solution = new OD0906c();

    @ParameterizedTest(name = "测试用例 {index}: packet={0}, expected={1}")
    @CsvSource(
            value = {
                    // ==================================================
                    // 1. 官方示例1
                    // ==================================================
                    //
                    // packet = 343873
                    //        = 0x00053F41
                    //
                    // status = 1
                    // id = 0
                    // dataType = 0
                    // factor = 244
                    // data = 5
                    //
                    // data = 0101，有2个1，偶校验通过
                    //
                    // 5 & 244
                    // 0000 0101
                    // 1111 0100
                    // ----------
                    // 0000 0100 = 4
                    "343873 | 4",

                    // ==================================================
                    // 2. 官方示例2
                    // ==================================================
                    // bit0 = 0，传感器故障
                    "0 | -1",

                    // ==================================================
                    // 3. 状态检查优先级
                    // ==================================================
                    // 即使后面的数据校验会失败，
                    // 只要bit0=0，就直接返回-1
                    "65536 | -1",

                    // ==================================================
                    // 4. 奇偶校验失败
                    // ==================================================
                    //
                    // 有效数据 = 1
                    // parity = 0
                    //
                    // 一共1个1，是奇数
                    "69617 | -2",

                    // ==================================================
                    // 5. 变长数据，有效长度为0
                    // ==================================================
                    //
                    // validData = 0
                    // parity = 0
                    // 校验通过
                    //
                    // 然后检查长度为0 -> -3
                    "4089 | -3",

                    // ==================================================
                    // 6. 检查顺序：
                    // 奇偶校验在长度0之前
                    // ==================================================
                    //
                    // dataType = 1
                    // validLength = 0
                    // parity = 1
                    //
                    // validData = 0
                    // 0 + parity的1 => 奇数
                    //
                    // 应该返回-2，而不是-3
                    "-2139422711 | -2",

                    // ==================================================
                    // 7. 寄存器ID = 1：按位或
                    // ==================================================
                    //
                    // data = 0101 = 5
                    // factor = 1010 = 10
                    //
                    // 0101
                    // 1010
                    // ----
                    // 1111 = 15
                    "327843 | 15",

                    // ==================================================
                    // 8. 寄存器ID = 2：按位异或
                    // ==================================================
                    //
                    // data   = 1010 = 10
                    // factor = 1100 = 12
                    //
                    // 1010
                    // 1100
                    // ----
                    // 0110 = 6
                    "655557 | 6",

                    // ==================================================
                    // 9. 寄存器ID = 3：按位同或
                    // ==================================================
                    //
                    // data   = 00001111
                    // factor = 11110000
                    //
                    // XOR = 11111111
                    // XNOR = ~11111111
                    //
                    // 最后再 & 0x0FFFFFFF
                    "986887 | 268435200",

                    // ==================================================
                    // 10. 同或 + mask 最明显的场景
                    // ==================================================
                    //
                    // data = 0
                    // factor = 0
                    //
                    // 0 ^ 0 = 0
                    // ~0 = 0xFFFFFFFF
                    //
                    // 0xFFFFFFFF & 0x0FFFFFFF
                    // = 0x0FFFFFFF
                    // = 268435455
                    "7 | 268435455",

                    // ==================================================
                    // 11. 变长数据：
                    // 高位无效数据必须被忽略
                    // ==================================================
                    //
                    // validLength = 3
                    //
                    // 原数据高位还有1，但是低3位为：
                    // 101 = 5
                    //
                    // 只有5参与：
                    // 1. 奇偶校验
                    // 2. 后续运算
                    //
                    // factor = 48
                    // registerId = 1
                    //
                    // 5 | 48 = 53
                    //
                    // 如果错误地把高位也参与校验，
                    // 这里会错误返回-2。
                    "268776203 | 53",

                    // ==================================================
                    // 12. bit31 = 1
                    // ==================================================
                    //
                    // Java int因此表现为负数
                    //
                    // validData = 1，有1个1
                    // parity = 1
                    //
                    // 总计2个1，偶校验通过
                    //
                    // 1 ^ 3 = 2
                    "-2147413955 | 2",

                    // ==================================================
                    // 13. 定长数据：
                    // bit16~bit30全部参与校验
                    // ==================================================
                    //
                    // data只有最高有效位bit14=1
                    // parity=1
                    //
                    // 总共2个1，校验通过
                    //
                    // data & 255 = 0
                    "-1073737743 | 0",

                    // ==================================================
                    // 14. 变长数据，有效长度15
                    // ==================================================
                    //
                    // data = 0x7FFF
                    // 共15个1
                    //
                    // parity = 1
                    // 总共16个1，偶校验通过
                    //
                    // factor=255
                    //
                    // 0x7FFF & 0xFF = 255
                    "-7 | 255",

                    // ==================================================
                    // 15. 有效数据为0
                    // ==================================================
                    //
                    // registerId = 1
                    // factor = 0x5A = 90
                    //
                    // 0 | 90 = 90
                    "1443 | 90"
            },
            delimiter = '|'
    )
    void testParsePacket(int packet, int expected) {

        int actual = solution.parsePacket(packet);

        assertEquals(expected, actual);
    }
}