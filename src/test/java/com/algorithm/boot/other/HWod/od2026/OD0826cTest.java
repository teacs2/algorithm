    void testCalculatePerformance(
            int n,
            String leftStr,
            String rightStr,
            String baseStr,
            String expectedStr) {

        int[] left = parseArray(leftStr);
        int[] right = parseArray(rightStr);
        int[] base = parseArray(baseStr);
        int[] expected = parseArray(expectedStr);

        int[] actual = solution.calculatePerformance(
                n,
                left,
                right,
                base
        );

        assertArrayEquals(expected, actual);
    }

    /**
     * 最大规模测试。
     * <p>
     * 构造1000个员工的左斜树：
     * <p>
     * 0
     * |
     * 1
     * |
     * 2
     * |
     * ...
     * |
     * 999
     * <p>
     * 每人基础绩效10000。
     * <p>
     * 员工999 = 10000
     * 员工998 = 20000
     * ...
     * 员工0   = 10000000
     */
    @Test
    void testMaxN() {
        int n = 1000;

        int[] left = new int[n];
        int[] right = new int[n];
        int[] base = new int[n];
        int[] expected = new int[n];

        for (int i = 0; i < n; i++) {
            left[i] = i == n - 1 ? -1 : i + 1;
            right[i] = -1;
            base[i] = 10000;

            expected[i] = (n - i) * 10000;
        }

        int[] actual = solution.calculatePerformance(
                n,
                left,
                right,
                base
        );

        assertArrayEquals(expected, actual);
    }

    /**
     * "1,3,-1,-1"
     * <p>
     * ->
     * <p>
     * new int[]{1,3,-1,-1}
     */
    private int[] parseArray(String str) {
        String s = str.trim();

        if (s.startsWith("[") && s.endsWith("]")) {
            s = s.substring(1, s.length() - 1);
        }

        if (s.isEmpty()) {
            return new int[0];
        }

        String[] parts = s.split(",");

        int[] result = new int[parts.length];

        for (int i = 0; i < parts.length; i++) {
            result[i] = Integer.parseInt(parts[i].trim());
        }

        return result;
    }
