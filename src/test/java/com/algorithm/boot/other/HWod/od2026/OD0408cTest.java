package com.algorithm.boot.other.HWod.od2026;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;

class OD0408cTest {

    private final OD0408c solution = new OD0408c();

    @ParameterizedTest(
            name = "测试用例 {index}: n={0}, sentries={1}, expected=[{2},{3}]"
    )
    @CsvSource(
            value = {
                    // ==================================================
                    // 1. 官方示例1：哨兵封锁整个3×3地图
                    // ==================================================
                    "3 | [[1,1]] | 0 | 0",

                    // ==================================================
                    // 2. 官方示例2：只有一条最短路径
                    // ==================================================
                    "5 | [[2,1]] | 1 | 7",

                    // ==================================================
                    // 3. 官方示例3：左右各有一条最短路径
                    // ==================================================
                    "5 | [[2,2]] | 2 | 9",

                    // ==================================================
                    // 4. 最小地图且没有哨兵
                    // ==================================================
                    // 从入口竖直向下，路径包含3个坐标
                    "3 | [] | 1 | 3",

                    // ==================================================
                    // 5. 没有哨兵时，竖直路径唯一且最短
                    // ==================================================
                    "5 | [] | 1 | 5",

                    // ==================================================
                    // 6. 哨兵位于左边界，监控区域需要裁剪
                    // ==================================================
                    // 中间一列不受影响，仍可竖直通过
                    "5 | [[2,0]] | 1 | 5",

                    // ==================================================
                    // 7. 官方示例2的左右镜像
                    // ==================================================
                    "5 | [[2,3]] | 1 | 7",

                    // ==================================================
                    // 8. 两个九宫格组成完整横向封锁
                    // ==================================================
                    "5 | [[2,1],[2,3]] | 0 | 0",

                    // ==================================================
                    // 9. 入口位于哨兵监控区域
                    // ==================================================
                    "5 | [[1,2]] | 0 | 0",

                    // ==================================================
                    // 10. 司令部位于哨兵监控区域
                    // ==================================================
                    "5 | [[3,2]] | 0 | 0",

                    // ==================================================
                    // 11. 7×7地图中央存在一个哨兵
                    // ==================================================
                    // 最短路径需要从九宫格两侧绕行
                    "7 | [[3,3]] | 18 | 11",

                    // ==================================================
                    // 12. 9×9地图中央存在一个哨兵
                    // ==================================================
                    "9 | [[4,4]] | 72 | 13",

                    // ==================================================
                    // 13. 两个哨兵分居两侧，中间通道保持畅通
                    // ==================================================
                    "9 | [[4,2],[4,6]] | 1 | 9",

                    // ==================================================
                    // 14. 两个九宫格逼迫路径从地图边缘绕行
                    // ==================================================
                    "7 | [[3,2],[3,4]] | 32 | 13",

                    // ==================================================
                    // 15. 错位障碍产生多条等长最短路径
                    // ==================================================
                    "7 | [[2,2],[4,4]] | 12 | 13",

                    // ==================================================
                    // 16. 哨兵位于左右边界，不影响中间直线路径
                    // ==================================================
                    "7 | [[3,0],[3,6]] | 1 | 7",

                    // ==================================================
                    // 17. 哨兵位于左上角，九宫格不能越过地图边界
                    // ==================================================
                    "5 | [[0,0]] | 1 | 5"
            },
            delimiter = '|'
    )
    void testFindShortestPaths(
            int n,
            String sentriesStr,
            int expectedCount,
            int expectedLength) {

        int[][] sentries = parseMatrix(sentriesStr);
        int[] expected = {expectedCount, expectedLength};

        int[] actual = solution.findShortestPaths(n, sentries);

        assertArrayEquals(expected, actual);
    }

    /**
     * 题目允许的最大奇数边长为29。
     * 没有哨兵时，唯一最短路径是从入口竖直走到司令部，
     * 路径包含29个坐标。
     */
    @Test
    void testMaximumMapSizeWithoutSentries() {
        assertArrayEquals(
                new int[]{1, 29},
                solution.findShortestPaths(29, new int[0][0])
        );
    }

    /**
     * 将字符串形式的坐标列表转换为 int[][]。
     * 例如：[[2,1],[2,3]]。
     */
    private int[][] parseMatrix(String str) {
        String content = str.replace(" ", "").trim();

        if ("[]".equals(content)) {
            return new int[0][0];
        }

        content = content.substring(2, content.length() - 2);
        String[] rows = content.split("\\],\\[");
        int[][] result = new int[rows.length][];

        for (int row = 0; row < rows.length; row++) {
            String[] values = rows[row].split(",");
            result[row] = new int[values.length];

            for (int col = 0; col < values.length; col++) {
                result[row][col] = Integer.parseInt(values[col]);
            }
        }

        return result;
    }
}
