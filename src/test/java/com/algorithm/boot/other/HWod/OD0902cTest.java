package com.algorithm.boot.other.HWod;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

import static org.junit.jupiter.api.Assertions.assertEquals;

class OD0902cTest {

    private final OD0902c solution = new OD0902c();

    @ParameterizedTest(name = "测试用例 {index}: towers={0}, expected={1}")
    @CsvSource(
            value = {
                    // ==================================================
                    // 1. 官方示例1
                    // ==================================================
                    // A(1,2), B(3,1), C(2,3)
                    //
                    // 最优：
                    // O -> A = 3
                    // A -> C = 2
                    // C -> B = 3
                    //
                    // 总距离 = 8
                    "[[1,2],[3,1],[2,3]] | 8",

                    // ==================================================
                    // 2. 官方示例2
                    // ==================================================
                    // O -> (1,1) = 2
                    // (1,1) -> (2,2) = 2
                    //
                    // 总距离 = 4
                    "[[1,1],[2,2]] | 4",

                    // ==================================================
                    // 3. 单个电力塔
                    // ==================================================
                    // 只需要从基地飞过去
                    // |5| + |7| = 12
                    "[[5,7]] | 12",

                    // ==================================================
                    // 4. 电力塔就在基地
                    // ==================================================
                    "[[0,0]] | 0",

                    // ==================================================
                    // 5. 多个塔在同一直线上
                    // ==================================================
                    // O -> (0,5) -> (0,10) -> (0,15)
                    // 5 + 5 + 5 = 15
                    "[[0,5],[0,10],[0,15]] | 15",

                    // ==================================================
                    // 6. 输入顺序不是最优顺序
                    // ==================================================
                    // 最优：
                    // O -> (1,0) -> (2,0) -> (3,0)
                    //
                    // 总距离 = 3
                    "[[3,0],[1,0],[2,0]] | 3",

                    // ==================================================
                    // 7. 重复坐标
                    // ==================================================
                    // O -> (1,1) = 2
                    // 两个塔坐标相同，第二段距离0
                    "[[1,1],[1,1]] | 2",

                    // ==================================================
                    // 8. 两个方向完全不同
                    // ==================================================
                    // O -> (0,2) = 2
                    // (0,2) -> (2,0) = 4
                    //
                    // 总距离 = 6
                    "[[0,2],[2,0]] | 6",

                    // ==================================================
                    // 9. 一个塔位于基地
                    // ==================================================
                    // 基地点不产生额外距离
                    "[[0,0],[2,2]] | 4",

                    // ==================================================
                    // 10. 专门测试：贪心最近点会失败
                    // ==================================================
                    //
                    // 如果每次选最近：
                    // O -> (0,1) -> (0,2) -> (0,3) -> (1,0)
                    // = 1 + 1 + 1 + 4 = 7
                    //
                    // 最优：
                    // O -> (1,0) -> (0,1) -> (0,2) -> (0,3)
                    // = 1 + 2 + 1 + 1 = 5
                    "[[0,1],[0,2],[0,3],[1,0]] | 5",

                    // ==================================================
                    // 11. 最大坐标
                    // ==================================================
                    //
                    // O -> (0,200) = 200
                    // -> (200,200) = 200
                    // -> (200,0) = 200
                    //
                    // 总距离600
                    "[[0,200],[200,0],[200,200]] | 600",

                    // ==================================================
                    // 12. 三个相邻点
                    // ==================================================
                    // O -> (0,1) = 1
                    // -> (1,1) = 1
                    // -> (1,0) = 1
                    //
                    // 总距离3
                    "[[0,1],[1,0],[1,1]] | 3",

                    // ==================================================
                    // 13. 方形结构
                    // ==================================================
                    // O -> (2,2) = 4
                    // 后面三个相邻移动，每次1
                    // 总计7
                    "[[2,2],[2,3],[3,2],[3,3]] | 7",

                    // ==================================================
                    // 14. 远点和近点混合
                    // ==================================================
                    //
                    // O -> (1,1) = 2
                    // -> (2,2) = 2
                    // -> (10,10) = 16
                    //
                    // 总距离20
                    "[[10,10],[1,1],[2,2]] | 20"
            },
            delimiter = '|'
    )
    void testMinDistance(String towersStr, int expected) {
        int[][] towers = parseMatrix(towersStr);

        int actual = solution.minDistance(towers);

        assertEquals(expected, actual);
    }

    /**
     * 测试题目最大规模 n = 15。
     * <p>
     * 坐标：
     * (1,1),(2,2),...,(15,15)
     * <p>
     * 最优路线显然是：
     * <p>
     * O -> (1,1) -> (2,2) -> ... -> (15,15)
     * <p>
     * O -> (1,1) = 2
     * 后面14段，每段距离2
     * <p>
     * 总距离：
     * 2 + 14 * 2 = 30
     */
    @Test
    void testMaxN() {
        int[][] towers = new int[15][2];

        for (int i = 0; i < 15; i++) {
            towers[i][0] = i + 1;
            towers[i][1] = i + 1;
        }

        assertEquals(30, solution.minDistance(towers));
    }

    /**
     * 非题目合法输入，仅检查代码健壮性。
     */
    @Test
    void testEmpty() {
        assertEquals(
                0,
                solution.minDistance(new int[0][0])
        );
    }

    /**
     * 非题目合法输入，仅检查代码健壮性。
     */
    @Test
    void testNull() {
        assertEquals(
                0,
                solution.minDistance(null)
        );
    }

    /**
     * 将：
     * <p>
     * [[1,2],[3,1],[2,3]]
     * <p>
     * 转换为：
     * <p>
     * new int[][]{
     * {1,2},
     * {3,1},
     * {2,3}
     * }
     */
    private int[][] parseMatrix(String str) {
        String s = str.replace(" ", "").trim();

        if ("[]".equals(s)) {
            return new int[0][0];
        }

        // 去掉最外层的 [[ 和 ]]
        s = s.substring(2, s.length() - 2);

        String[] rows = s.split("\\],\\[");

        int[][] result = new int[rows.length][];

        for (int i = 0; i < rows.length; i++) {
            String[] nums = rows[i].split(",");

            result[i] = new int[nums.length];

            for (int j = 0; j < nums.length; j++) {
                result[i][j] = Integer.parseInt(nums[j]);
            }
        }

        return result;
    }
}